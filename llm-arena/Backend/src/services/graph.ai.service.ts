import { HumanMessage } from "@langchain/core/messages";
import {
  StateSchema,
  MessagesValue,
  ReducedValue,
  StateGraph,
  START,
  END,
  MessagesAnnotation,
} from "@langchain/langgraph";
import type { GraphNode } from "@langchain/langgraph";
import {
  mistralModel,
  cohereModel,
  geminiModel,
  MISTRAL_PROVIDER_LABEL,
  COHERE_PROVIDER_LABEL,
} from "./models.service.js";
import { createAgent, providerStrategy } from "langchain";
import { z } from "zod";

const State = new StateSchema({

  problem: z.string().default(""),
  solution_1: z.string().default(""),
  solution_1_provider: z.string().default(""),
  solution_2: z.string().default(""),
  solution_2_provider: z.string().default(""),
  judge: z.object({
    solution_1_score: z.number().default(0),
    solution_2_score: z.number().default(0),
    solution_1_reasoning: z.string().default(""),
    solution_2_reasoning: z.string().default(""),
  })
});

const solutionNode: GraphNode< typeof State.State > = async (state) => {
   const [mistralResponse, cohereResponse] = await Promise.all([
    mistralModel.invoke(state.problem),
    cohereModel.invoke(state.problem),
  ]);

  return {
    solution_1:
      typeof mistralResponse.content === "string"
        ? mistralResponse.content
        : JSON.stringify(mistralResponse.content),
    solution_1_provider: MISTRAL_PROVIDER_LABEL,
    solution_2:
      typeof cohereResponse.content === "string"
        ? cohereResponse.content
        : JSON.stringify(cohereResponse.content),
    solution_2_provider: COHERE_PROVIDER_LABEL,
  };
};

const judgeNode: GraphNode< typeof State.State > = async (state) => {

  const {problem , solution_1 , solution_2} = state
  
  const judge = createAgent({
    model: geminiModel,
    responseFormat:providerStrategy(
      z.object({
        solution_1_score:z.number().min(0).max(10),
        solution_2_score:z.number().min(0).max(10),
        solution_1_reasoning:z.string(),
        solution_2_reasoning:z.string(),
      })),

      systemPrompt:`
      You are a helpful assistant that evaluates the quality of solutions provided by different language models. You will be given a problem: ${problem} statement and two solutions generated by two different models. Your task is to compare the two solutions and provide a score to both based on their quality. The score should be between 0 and 10 where 10 is the best and 0 is the worst.

      The solutions should be evaluated based on the following criteria:
      1. Accuracy: Is the solution correct?
      2. Completeness: Does the solution address all aspects of the problem?
      3. Clarity: Is the solution easy to understand?
      4. Conciseness: Is the solution concise and to the point?
      5. Relevance: Is the solution relevant to the problem statement?
      
      The solutions should be compared against the problem statement and the criteria mentioned above. The comparison should be done in a fair and unbiased manner. 
      `,
  });

  const judgeResponse = await judge.invoke({
    messages: [
      new HumanMessage(
        `
        Problem: ${problem}
        Solution 1: ${solution_1}
        Solution 2: ${solution_2}
        please evaluate the solutions and provide scores and reasoning.
        `
      )
    ]
  });

  const {
    solution_1_score,
    solution_2_score,
    solution_1_reasoning,
    solution_2_reasoning
  } = judgeResponse.structuredResponse;

  return {
    judge: {
      solution_1_score,
      solution_2_score,
      solution_1_reasoning,
      solution_2_reasoning,
    }
  };
};

const graph = new StateGraph(State)
  .addNode("solution", solutionNode)
  .addNode("judge_node", judgeNode)
  .addEdge(START, "solution")
  .addEdge("solution", "judge_node")
  .addEdge("judge_node", END)
  .compile();

export default async function (problem: string) {
  const result = await graph.invoke({
    problem: problem,
  });

  return result;
}
